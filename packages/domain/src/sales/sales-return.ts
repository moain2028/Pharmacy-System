interface SalesReturnProps {
  readonly returnId: string;
  readonly invoiceId: string | null;
  readonly customerId: string | null;
  readonly currency: CurrencyCode;
  readonly businessDate: IsoDate;
  readonly status: DocumentStatus;
  readonly reason: ReturnReason;
  readonly lines: readonly ReturnLine[];
  readonly refunds: readonly RefundTender[];
}

export class SalesReturn {
  readonly returnId: string;
  readonly invoiceId: string | null;
  readonly customerId: string | null;
  readonly currency: CurrencyCode;
  readonly businessDate: IsoDate;
  readonly status: DocumentStatus;
  readonly reason: ReturnReason;
  readonly lines: readonly ReturnLine[];
  readonly refunds: readonly RefundTender[];

  private constructor(p: SalesReturnProps) {
    this.returnId = p.returnId;
    this.invoiceId = p.invoiceId;
    this.customerId = p.customerId;
    this.currency = p.currency;
    this.businessDate = p.businessDate;
    this.status = p.status;
    this.reason = p.reason;
    this.lines = Object.freeze([...p.lines]);
    this.refunds = Object.freeze([...p.refunds]);
    Object.freeze(this);
  }

  /** Return against a posted invoice (FR-SAL-147..153). */
  static create(req: SalesReturnRequest, policy: ReturnPolicy): Result<SalesReturn> {
    const inv = req.invoice;
    if (inv.status !== "POSTED") {
      return domainErr("return.invoice_not_posted", "Returns are only possible against a POSTED invoice", { status: inv.status });
    }
    const reason = validateReason(req.reason);
    if (!reason.ok) return reason;
    if (req.lines.length === 0) return domainErr("return.no_lines", "A return needs at least one line");
    const age = daysBetween(inv.businessDate, req.businessDate);
    if (age < 0) return domainErr("return.before_sale", "Return date precedes the invoice date", { invoiceDate: inv.businessDate });
    const perms = new Set(req.permissions);
    const seen = new Set<string>();
    const lines: ReturnLine[] = [];
    for (const rl of req.lines) {
      if (seen.has(rl.lineId)) return domainErr("return.duplicate_line", "Line listed twice", { lineId: rl.lineId });
      seen.add(rl.lineId);
      const sold = inv.lines.find((l) => l.lineId === rl.lineId);
      if (sold === undefined) return domainErr("return.unknown_line", "Line does not belong to the invoice", { lineId: rl.lineId });
      const window = sold.returnWindowDays ?? policy.defaultReturnWindowDays;
      if (age > window && !perms.has(RETURN_PERMISSIONS.late)) {
        return domainErr("return.window_expired", "Return window expired; supervisor permission required", {
          lineId: rl.lineId, ageDays: age, windowDays: window, permission: RETURN_PERMISSIONS.late,
        });
      }
      const built = buildLine(sold, rl.qtySsu, inv.currency, req.businessDate, perms);
      if (!built.ok) return built;
      lines.push(built.value);
    }
    const refundTotal = Money.sum(lines.map((l) => l.refundMinor), inv.currency);
    const refunds = buildRefunds(refundTotal, inv.payments, req.refundToCustomerCredit === true);
    if (!refunds.ok) return refunds;
    return ok(new SalesReturn({
      returnId: req.returnId, invoiceId: inv.invoiceId, customerId: inv.customerId, currency: inv.currency,
      businessDate: req.businessDate, status: "DRAFT", reason: reason.value, lines, refunds: refunds.value,
    }));
  }

  /** Return without an original invoice (FR-SAL-152): permission, min price, quarantine. */
  static createWithoutInvoice(req: ReturnWithoutInvoiceRequest): Result<SalesReturn> {
    if (!req.permissions.includes(RETURN_PERMISSIONS.withoutInvoice)) {
      return domainErr("return.permission_required", "Returns without invoice require a permission", { permission: RETURN_PERMISSIONS.withoutInvoice });
    }
    const reason = validateReason(req.reason);
    if (!reason.ok) return reason;
    if (req.qtySsu <= 0n) return domainErr("return.non_positive_qty", "Return quantity must be > 0");
    const cur = req.currentPriceSsu.currency;
    if (req.lastSalePriceSsu.currency !== cur || req.unitCostSsu.currency !== cur) {
      return domainErr("return.currency_mismatch", "Prices and cost must share one currency");
    }
    if (req.currentPriceSsu.isNegative() || req.lastSalePriceSsu.isNegative() || req.unitCostSsu.isNegative()) {
      return domainErr("return.negative_amount", "Prices and cost must be >= 0");
    }
    const refund = Money.min(req.currentPriceSsu, req.lastSalePriceSsu).multiply(req.qtySsu);
    const cost = req.unitCostSsu.multiply(req.qtySsu);
    const lot: ReturnLotIntent = Object.freeze({
      type: "SALE_RETURN", lineId: null, itemId: req.itemId, lotId: req.newLotId, qtySsu: req.qtySsu, costMinor: cost, destination: "QUARANTINED",
    });
    const line: ReturnLine = Object.freeze({ lineId: null, itemId: req.itemId, qtySsu: req.qtySsu, refundMinor: refund, costMinor: cost, lots: [lot] });
    const refunds: RefundTender[] = refund.isPositive()
      ? [Object.freeze({ method: req.refundToCustomerCredit === true ? "CUSTOMER_CREDIT" : "CASH", amount: refund })]
      : [];
    return ok(new SalesReturn({
      returnId: req.returnId, invoiceId: null, customerId: req.customerId ?? null, currency: cur, businessDate: req.businessDate,
      status: "DRAFT", reason: reason.value, lines: [line], refunds,
    }));
  }

  get refundTotal(): Money {
    return Money.sum(this.lines.map((l) => l.refundMinor), this.currency);
  }

  get cogsReversal(): Money {
    return Money.sum(this.lines.map((l) => l.costMinor), this.currency);
  }

  lotIntents(): readonly ReturnLotIntent[] {
    return Object.freeze(this.lines.flatMap((l) => [...l.lots]));
  }

  /** DRAFT → POSTED; returns a new instance (B5: posted documents are never mutated). */
  post(): Result<SalesReturn> {
    if (this.status !== "DRAFT") return domainErr("return.already_posted", "Only a DRAFT return can be posted", { status: this.status });
    return ok(new SalesReturn({ ...this, status: "POSTED" }));
  }

  postingIntent(): Result<SalesReturnPostingIntent> {
    if (this.status !== "POSTED") return domainErr("return.not_posted", "Posting intent is only available for a POSTED return", { status: this.status });
    return ok(Object.freeze({
      documentRef: Object.freeze({ type: "SALES_RETURN" as const, id: this.returnId }),
      refundTotal: this.refundTotal,
      cogsReversal: this.cogsReversal,
      lotCosts: Object.freeze(this.lotIntents().map((l) => Object.freeze({ itemId: l.itemId, lotId: l.lotId, cost: l.costMinor }))),
      refunds: this.refunds,
    }));
  }
}
