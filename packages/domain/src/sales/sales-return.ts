/**
 * Sales returns (FR-SAL-147..153, FR-SAL-156; POS spec edge cases 1-2).
 *
 * - Drafted against a POSTED invoice snapshot; per line, qty <= sold − already returned (FR-SAL-147).
 * - Refund of a line = its share of the line net (after line discount + invoice-discount allocation)
 *   computed with Money.allocate on the *cumulative* returned quantity, so successive partial returns
 *   sum exactly to the original net and never depend on today's price (FR-SAL-148, edge case 2).
 * - Quantities go back to the lots they were issued from, last allocated lot first, at the original
 *   lot cost (FR-SAL-149). Expired or non-NONE lots → QUARANTINED; non-returnable items (only with
 *   `returns.non_returnable`) → BLOCKED (FR-SAL-150). Late returns need `returns.late` (FR-SAL-151).
 * - Refund tenders mirror the original payment: CREDIT is reduced first, the rest proportionally over
 *   the other tenders, or as customer credit when requested (FR-SAL-153).
 * - Returns without invoice need `returns.without_invoice`; price = min(current, last sale) and the
 *   quantity is quarantined in a new lot the application pre-allocates (FR-SAL-152).
 * The application turns `lotIntents()` into SALE_RETURN stock movements and `postingIntent()` into
 * the journal entry; this module stays pure.
 */
