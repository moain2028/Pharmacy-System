export const DOCUMENT_STATUSES = ["DRAFT", "HELD", "POSTED", "REVERSED"] as const;
export type DocumentStatus = (typeof DOCUMENT_STATUSES)[number];

export const RETURN_PERMISSIONS = Object.freeze({
  withoutInvoice: "returns.without_invoice",
  late: "returns.late",
  nonReturnable: "returns.non_returnable",
} as const);
export type ReturnPermission = (typeof RETURN_PERMISSIONS)[keyof typeof RETURN_PERMISSIONS];

export const RETURN_DESTINATIONS = ["AVAILABLE", "QUARANTINED", "BLOCKED"] as const;
export type ReturnDestination = (typeof RETURN_DESTINATIONS)[number];

export type RefundMethod = TenderMethod | "CUSTOMER_CREDIT";

export interface SoldLotSnapshot {
  readonly lotId: string;
  readonly qtySsu: bigint;
  readonly returnedQtySsu: bigint;
  /** Cost of the whole allocation (sale_line_lot qty × unit cost). */
  readonly costMinor: Money;
  readonly expiryDate: IsoDate;
  readonly manualStatus: LotManualStatus;
}

export interface SoldLineSnapshot {
  readonly lineId: string;
  readonly itemId: string;
  readonly qtySsu: bigint;
  readonly returnedQtySsu: bigint;
  /** net_amt after line discount and inv_disc_alloc, in the invoice currency. */
  readonly netMinor: Money;
  /** false = `non_returnable` item (FR-SAL-150). */
  readonly returnable: boolean;
  /** Item-specific `return_window_days`; falls back to the policy default. */
  readonly returnWindowDays?: number | undefined;
  readonly lots: readonly SoldLotSnapshot[];
}

export interface PaidPortion {
  readonly method: TenderMethod;
  /** In the invoice currency (amount_func). */
  readonly amount: Money;
}

